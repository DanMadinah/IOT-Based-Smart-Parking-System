#!/usr/bin/env python3
"""
Bundles web/ HTML, CSS, and JS files into firmware/smart_parking/web_pages.h
as PROGMEM raw string literals for the ESP32 WebServer.

Usage:
    python scripts/build_web_header.py
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
WEB_DIR = ROOT / "web"
OUT_FILE = ROOT / "firmware" / "smart_parking" / "web_pages.h"

PAGES = [
    ("PAGE", "index.html"),
    ("ADMIN_PAGE", "admin.html"),
    ("ABOUT_PAGE", "about.html"),
]


def inline_assets(html_path: Path) -> str:
    html = html_path.read_text(encoding="utf-8")

    def replace_css(match: re.Match) -> str:
        href = match.group(1)
        css_path = (html_path.parent / href).resolve()
        css = css_path.read_text(encoding="utf-8").strip()
        return f"<style>\n{css}\n</style>"

    def replace_js(match: re.Match) -> str:
        src = match.group(1)
        if src.endswith(("demo-mock.js", "firebase-config.js", "firebase-bridge.js")):
            return ""
        js_path = (html_path.parent / src).resolve()
        js = js_path.read_text(encoding="utf-8").strip()
        return f"<script>\n{js}\n</script>"

    html = re.sub(
        r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s*/?>',
        replace_css,
        html,
    )
    html = re.sub(
        r'<script\s+src="([^"]+)"></script>',
        replace_js,
        html,
    )
    return html.strip()


def main() -> None:
    lines = [
        "#ifndef WEB_PAGES_H",
        "#define WEB_PAGES_H",
        "",
        "#include <pgmspace.h>",
        "",
        "// Auto-generated by scripts/build_web_header.py — edit files in web/ instead.",
        "",
    ]

    for symbol, filename in PAGES:
        bundled = inline_assets(WEB_DIR / filename)
        if ")rawliteral" in bundled:
            raise ValueError(f"{filename} contains ')rawliteral', which breaks C++ raw strings.")
        lines.append(f'static const char {symbol}[] PROGMEM = R"rawliteral(')
        lines.append(bundled)
        lines.append(')rawliteral";')
        lines.append("")

    lines.append("#endif // WEB_PAGES_H")
    lines.append("")

    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUT_FILE.relative_to(ROOT)} ({OUT_FILE.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
